import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const service = resolve(process.env.GONGBU_PROJECT_DIR || resolve(root, "../gongbu-eong"));
const viewRoot = "features/admin/components/members/service-results/diagnosis";
const dataRoot = "features/admin/server/service-diagnosis";
const check = process.argv.includes("--check");
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
const header = "// Generated by scripts/sync-diagnosis-results.mjs. Do not edit.\n";
const outputs = new Map();
const manifest = {};
const read = async path => {
  const bytes = await readFile(resolve(service, path));
  manifest[path] = createHash("sha256").update(/\.(tsx?|css)$/.test(path) ? bytes.toString().replace(/\r\n/g, "\n") : bytes).digest("hex");
  return bytes;
};
const parse = (name, source) => ts.createSourceFile(name, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const identifiers = nodes => {
  const names = new Set();
  const visit = node => { if (ts.isIdentifier(node)) names.add(node.text); ts.forEachChild(node, visit); };
  nodes.forEach(visit);
  return names;
};
const declarationName = node => ts.isVariableStatement(node)
  ? node.declarationList.declarations[0]?.name.getText()
  : node.name?.text;

// Copy only read-only declarations and their local dependencies, not service mutations.
function extract(file, roots, importPaths = {}) {
  const declarations = new Map(file.statements.map(node => [declarationName(node), node]).filter(([name]) => name));
  const selected = new Set(roots);
  for (const name of selected) {
    const node = declarations.get(name);
    if (!node) throw new Error(`Missing declaration: ${name}`);
    for (const dependency of identifiers([node])) if (declarations.has(dependency)) selected.add(dependency);
  }
  const nodes = file.statements.filter(node => selected.has(declarationName(node)));
  const names = identifiers(nodes);
  const imports = file.statements.filter(ts.isImportDeclaration).flatMap(node => {
    const clause = node.importClause;
    if (!clause) return [];
    const defaultName = clause.name && names.has(clause.name.text) ? clause.name : undefined;
    const bindings = clause.namedBindings && ts.isNamedImports(clause.namedBindings)
      ? clause.namedBindings.elements.filter(entry => names.has(entry.name.text)) : [];
    if (!defaultName && !bindings.length) return [];
    return [ts.factory.updateImportDeclaration(node, node.modifiers,
      ts.factory.updateImportClause(clause, clause.isTypeOnly, defaultName, bindings.length ? ts.factory.createNamedImports(bindings) : undefined),
      ts.factory.createStringLiteral(importPaths[node.moduleSpecifier.text] || node.moduleSpecifier.text), node.attributes)];
  });
  const exported = nodes.map(node => roots.includes(declarationName(node)) && !node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
    ? ts.factory.replaceModifiers(node, [ts.factory.createModifier(ts.SyntaxKind.ExportKeyword), ...(node.modifiers || [])]) : node);
  return ts.factory.updateSourceFile(file, [...imports, ...exported]);
}

const dataFiles = [
  ["diagnosis/diagnosis.repository", ["findDiagnosisResultForUser", "findLatestDiagnosisResultForUser", "findDiagnosisPercentile", "countPreviousDiagnosisResults", "findJobCategoriesForPersonalityType", "findRecommendedInstitutions", "findMonthlyHiringByPersonalityType"]],
  ["diagnosis/diagnosis.service", ["toDiagnosisResultResponse", "PERCENTILE_TRAIT_LABELS"]],
  ["jobs/jobs.repository", ["findRecommendedJobPostings"]],
  ["jobs/jobs.service", ["toJobPostingDto"]],
];
for (const [name, roots] of dataFiles) {
  const file = parse(`${name}.ts`, (await read(`gongbu-eong-backend/domains/${name}.ts`)).toString());
  const output = printer.printFile(extract(file, roots, { "@/lib/db": "@/features/admin/server/db" }));
  if (/\b(INSERT INTO|UPDATE public\.|DELETE FROM)\b/.test(output)) throw new Error(`Unexpected mutation in ${name}`);
  outputs.set(`${dataRoot}/${name}.ts`, header + output);
}
for (const kind of ["diagnosis", "jobs"]) {
  outputs.set(`${dataRoot}/${kind}/${kind}.dto.ts`, await read(`gongbu-eong-backend/domains/${kind}/${kind}.dto.ts`));
}

const source = parse("DiagnosisResultDetail.tsx", (await read("gongbu-eong-event/features/diagnosis/components/DiagnosisResultDetail.tsx")).toString());
const original = source.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === "DiagnosisResultDetail");
const keptVariables = new Set(["points", "{ result }", "copy", "heroOwnerLabel", "personTitle", "subjectLabel", "displayedJobCategories", "maxHiringCount"]);
const body = original.body.statements.filter(node => ts.isVariableStatement(node) && keptVariables.has(declarationName(node)));
const returnNode = original.body.statements.findLast(ts.isReturnStatement);
const signature = parse("view.tsx", `export function DiagnosisResultDetail({ detail, nickname }: { detail: DiagnosisResultDetailResponseDto; nickname: string }) { const isPublicView = false; }`).statements[0];
const view = ts.factory.updateFunctionDeclaration(signature, signature.modifiers, signature.asteriskToken, signature.name,
  signature.typeParameters, signature.parameters, signature.type, ts.factory.createBlock([...signature.body.statements, ...body, returnNode], true));
const helpers = extract(source, ["TYPE_COPY", "POINT_TITLES", "FigmaSectionIcon", "RecommendedPosting", "formatPostingDate"], {
  "@/features/jobs/job-display": "./job-display",
});
const importsAndHelpers = helpers.statements.filter(node => !["mainAppUrl", "mainHref"].includes(declarationName(node)));
const prelude = `"use client";
import { useMemo } from "react";
import { publicSiteHref as mainHref } from "@/features/admin/public-site";
`;
let adapted = ts.factory.updateSourceFile(source, [...importsAndHelpers, view]);
// Strip account-changing, sharing and cross-service navigation controls only.
const transformed = ts.transform(adapted, [context => {
  const visit = node => {
    if (ts.isJsxExpression(node) && /styles\.(actions|historyOverlay|coachingButton)/.test(node.getText(source))) return undefined;
    if (ts.isJsxSelfClosingElement(node) && ["AppHeader", "AppFooter"].includes(node.tagName.getText(source))) {
      return ts.factory.createNull();
    }
    return ts.visitEachChild(node, visit, context);
  };
  return file => ts.visitNode(file, visit);
}]);
adapted = transformed.transformed[0];
// Imports are collected from helpers; remove the duplicate stylesheet import.
const seenImports = new Set();
adapted = ts.factory.updateSourceFile(adapted, adapted.statements.filter(node => {
  if (!ts.isImportDeclaration(node)) return true;
  const key = node.moduleSpecifier.text;
  if (seenImports.has(key)) return false;
  seenImports.add(key);
  return true;
}));
outputs.set(`${viewRoot}/DiagnosisResultDetail.tsx`, header + prelude + printer.printFile(adapted));
transformed.dispose();
outputs.set(`${viewRoot}/DiagnosisResultDetail.module.css`, await read("gongbu-eong-event/features/diagnosis/components/DiagnosisResultDetail.module.css"));
// Keep the relative DTO import used by the original presentation helpers.
outputs.set("features/admin/components/members/service-results/diagnosis.dto.ts", await read("gongbu-eong-event/features/diagnosis/diagnosis.dto.ts"));
outputs.set(`${viewRoot}/job-display.ts`, await read("gongbu-eong-event/features/jobs/job-display.ts"));

const assets = ["title-icon.png", "strength-1.svg", "strength-2.svg", "strength-3.svg", "growth.svg", "bookmark.svg", "figma-result-reference.png"]
  .map(name => `diagnosis/result-detail/${name}`);
for (const type of ["stability", "challenge", "teamwork", "individual", "execution", "planning", "principle", "flexibility"]) assets.push(`home/result-types/${type}.webp`);
