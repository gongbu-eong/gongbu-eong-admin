outputs.set(`${viewRoot}/source-manifest.json`, JSON.stringify(manifest, null, 2) + "\n");
for (const [path, source] of outputs) {
  const target = resolve(root, path);
  const bytes = Buffer.isBuffer(source) ? source : Buffer.from(source);
  if (check) {
    const current = await readFile(target);
    const normalize = value => /\.(tsx?|css|json)$/.test(path) ? value.toString().replace(/\r\n/g, "\n") : value;
    if (Buffer.isBuffer(normalize(bytes)) ? !current.equals(bytes) : normalize(current) !== normalize(bytes)) throw new Error(`Diagnosis result drift: ${path}`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, bytes);
  }
}
console.log(`${check ? "Verified" : "Synchronized"} ${outputs.size} diagnosis result files.`);
