import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = resolve(process.env.GONGBU_FRONTEND_DIR || resolve(root, "../gongbu-eong/gongbu-eong-frontend"));
const destination = resolve(root, "features/admin/components/members/service-results");
const check = process.argv.includes("--check");
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
const provenance = {};
const outputs = new Map();
const read = async (name) => {
  const source = await readFile(resolve(sourceRoot, name), "utf8");
  provenance[name] = createHash("sha256").update(source.replace(/\r\n/g, "\n")).digest("hex");
  return source;
};
const parse = (name, source) => ts.createSourceFile(name, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const header = "// Generated by scripts/sync-coaching-results.mjs from the public service. Do not edit.\n";

function filterImport(node, names) {
  const clause = node.importClause;
  if (!clause) return node;
  const defaultName = clause.name && names.has(clause.name.text) ? clause.name : undefined;
  const bindings = clause.namedBindings && ts.isNamedImports(clause.namedBindings)
    ? ts.factory.updateNamedImports(clause.namedBindings, clause.namedBindings.elements.filter((entry) => names.has(entry.name.text)))
    : undefined;
  if (!defaultName && !bindings?.elements.length) return undefined;
  return ts.factory.updateImportDeclaration(node, node.modifiers,
    ts.factory.updateImportClause(clause, clause.isTypeOnly, defaultName, bindings?.elements.length ? bindings : undefined),
    node.moduleSpecifier, node.attributes);
}

function identifiers(nodes) {
  const names = new Set();
  const visit = (node) => {
    if (ts.isIdentifier(node)) names.add(node.text);
    ts.forEachChild(node, visit);
  };
  nodes.forEach(visit);
  return names;
}

function isClassElement(node, className) {
  if (!ts.isJsxElement(node)) return false;
  return node.openingElement.attributes.properties.some((attribute) =>
    ts.isJsxAttribute(attribute) && attribute.name.text === "className"
    && attribute.initializer && ts.isJsxExpression(attribute.initializer)
    && attribute.initializer.expression?.getText().includes(`styles.${className}`));
}

function renderResult(sourceFile, kind) {
  const removedImports = new Set(["useRouter", "trackProductEvent", "AppHeader", "AppFooter", "getInterviewCoachingSession", "Link", "useEffect"]);
  const transform = (context) => {
    const visit = (node) => {
      if (ts.isImportDeclaration(node)) {
        const names = identifiers([node]);
        removedImports.forEach((name) => names.delete(name));
        const filtered = filterImport(node, names);
        if (filtered && filtered.moduleSpecifier.text === "./InterviewCoachingPage") {
          return ts.factory.updateImportDeclaration(filtered, filtered.modifiers, filtered.importClause,
            ts.factory.createStringLiteral("./InterviewResultShared"), filtered.attributes);
        }
        return filtered;
      }
      if (ts.isFunctionDeclaration(node) && node.name?.text === "InterviewCoachingResultPage") return undefined;
      if (ts.isVariableStatement(node) && node.declarationList.declarations.some((entry) =>
        ts.isIdentifier(entry.name) && ["viewedResult", "router"].includes(entry.name.text))) return undefined;
      if (ts.isExpressionStatement(node) && ts.isCallExpression(node.expression)
        && ts.isIdentifier(node.expression.expression) && node.expression.expression.text === "useEffect") return undefined;
      if (ts.isJsxSelfClosingElement(node) && ["AppHeader", "AppFooter"].includes(node.tagName.getText())) return undefined;
      if (ts.isJsxExpression(node) && node.expression && ts.isConditionalExpression(node.expression)
        && isClassElement(node.expression.whenTrue, "resultActions")) return undefined;
      if (ts.isJsxElement(node) && node.openingElement.tagName.getText() === "Link") return undefined;
      const result = ts.visitEachChild(node, visit, context);
      if (kind === "interview" && ts.isFunctionDeclaration(result) && result.name?.text === "ResultView") {
        return ts.factory.updateFunctionDeclaration(result, [ts.factory.createModifier(ts.SyntaxKind.ExportKeyword)],
          result.asteriskToken, "InterviewCoachingResultView", result.typeParameters, result.parameters, result.type, result.body);
      }
      return result;
    };
    return (node) => ts.visitNode(node, visit);
  };
  const result = ts.transform(sourceFile, [transform]);
  const output = header + printer.printFile(result.transformed[0]);
  result.dispose();
  if (/trackProductEvent|AppHeader|AppFooter|router\.push|coaching\.api/.test(output)) throw new Error("Service side effects were not removed");
  return output;
}

for (const [feature, name, kind] of [
  ["coaching", "CoachingResultView", "resume"],
  ["interview-coaching", "InterviewCoachingResultPage", "interview"],
]) {
  const source = await read(`features/${feature}/components/${name}.tsx`);
  outputs.set(`${feature}/components/${name}.tsx`, renderResult(parse(`${name}.tsx`, source), kind));
  const css = feature === "coaching" ? "CoachingPage.module.css" : "InterviewCoachingPage.module.css";
  outputs.set(`${feature}/components/${css}`, await read(`features/${feature}/components/${css}`));
  outputs.set(`${feature}/${feature}.dto.ts`, await read(`features/${feature}/${feature}.dto.ts`));
}

// Extract the actual presentation helpers, including their local dependencies.
const supportFile = parse("InterviewCoachingPage.tsx", await read("features/interview-coaching/components/InterviewCoachingPage.tsx"));
const declarations = new Map(supportFile.statements.filter((node) => ts.isFunctionDeclaration(node) && node.name).map((node) => [node.name.text, node]));
const selected = new Set(["InterviewAnalysisView", "QuestionTabs", "AnswerLoadingOverlay", "formatNcsReasonParagraphs"]);
for (const name of selected) {
  if (!declarations.has(name)) throw new Error(`Missing service helper: ${name}`);
  for (const dependency of identifiers([declarations.get(name)])) {
    if (declarations.has(dependency)) selected.add(dependency);
  }
}
const supportNodes = supportFile.statements.filter((node) => ts.isFunctionDeclaration(node) && selected.has(node.name?.text));
const usedNames = identifiers(supportNodes);
const imports = supportFile.statements.filter(ts.isImportDeclaration).map((node) => filterImport(node, usedNames)).filter(Boolean);
const support = ts.factory.updateSourceFile(supportFile, [
  ts.factory.createExpressionStatement(ts.factory.createStringLiteral("use client")), ...imports, ...supportNodes,
]);
outputs.set("interview-coaching/components/InterviewResultShared.tsx", header + printer.printFile(support));
outputs.set("source-manifest.json", JSON.stringify(provenance, null, 2) + "\n");

for (const [name, source] of outputs) {
  const filename = resolve(destination, name);
  if (check) {
    const current = await readFile(filename, "utf8");
    if (current.replace(/\r\n/g, "\n") !== source.replace(/\r\n/g, "\n")) throw new Error(`Service result drift: ${name}`);
  } else {
    await mkdir(dirname(filename), { recursive: true });
    await writeFile(filename, source);
  }
}
console.log(`${check ? "Verified" : "Synchronized"} ${outputs.size} service result files.`);
